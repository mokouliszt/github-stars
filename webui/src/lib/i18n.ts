const DICT: Record<Lang, Record<Key, Entry>> = { ja, en };

export function translate(lang: Lang, key: Key, vars: Vars = {}): string {
  const e = DICT[lang][key] ?? DICT.ja[key];
  if (typeof e === "function") return e(vars);
  return e.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export type T = (key: Key, vars?: Vars) => string;

/** Effort labels: known values are translated, anything new from Codex is shown as-is. */
export function effortLabel(t: T, e: string): string {
  const k = `eff_${e}` as Key;
  return k in ja ? t(k) : e;
}

export const I18nContext = React.createContext<{ lang: Lang; t: T }>({
  lang: "ja",
  t: (k, v) => translate("ja", k, v),
});

export const useI18n = () => React.useContext(I18nContext);
